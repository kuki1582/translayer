package com.example.trans_layer_app.ui.state

/**
 * フローティングボタンの表示状態を定義する列挙型。
 */
enum class FloatingButtonState {
    /**
     * 導入状態。ボタンが画面上に現れる際のアニメーション（バウンド等）を実行中の状態。
     */
    INTRO,

    /**
     * 左端折り畳み状態。画面の左端に吸着し、矢印などの最小限のインジケータを表示している状態。
     */
    LEFT_COLLAPSED,

    /**
     * 右端折り畳み状態。画面の右端に吸着し、矢印などの最小限のインジケータを表示している状態。
     */
    RIGHT_COLLAPSED,

    /**
     * 準備完了状態。ボタンが完全に表示され、ユーザーによる操作（翻訳開始など）を待機している通常の状態。
     */
    READY
}
